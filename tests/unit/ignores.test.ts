import { strict as assert } from 'node:assert';
import { describe, it } from 'node:test';
import { defaultIgnores, findIgnoreMatch, resolveIgnores } from '../../src/ignores.ts';
import { autoGenerated, notAutoGenerated, valid } from '../fixtures/messages.ts';

/** Match a message against the built-in default ignores. */
function matchDefault(message: string): string | null {
  return findIgnoreMatch(message, defaultIgnores);
}

describe('defaultIgnores', () => {
  describe('matches git-generated messages', () => {
    const cases: Array<[string, string]> = [
      [autoGenerated.revert, 'revert'],
      [autoGenerated.reapply, 'revert'],
      [autoGenerated.revertEmptySubject, 'revert'],
      [autoGenerated.mergeBranch, 'merge'],
      [autoGenerated.mergeBranchInto, 'merge'],
      [autoGenerated.mergeBranches, 'merge'],
      [autoGenerated.mergePullRequest, 'merge'],
      [autoGenerated.mergeRemoteTracking, 'merge'],
      [autoGenerated.mergeTag, 'merge'],
      [autoGenerated.mergeCommit, 'merge'],
      [autoGenerated.fixup, 'fixup'],
      [autoGenerated.squash, 'squash'],
      [autoGenerated.amend, 'amend'],
    ];

    for (const [message, expected] of cases) {
      it(`matches ${JSON.stringify(message.split('\n')[0])} as "${expected}"`, () => {
        assert.equal(matchDefault(message), expected);
      });
    }

    it('matches a fixup of a fixup', () => {
      assert.equal(matchDefault('fixup! fixup! feat: add login'), 'fixup');
    });

    it('tests only the first line (multiline revert)', () => {
      assert.equal(matchDefault('Revert "feat: x"\n\nfix: not a revert body'), 'revert');
    });

    it('handles CRLF line endings', () => {
      assert.equal(matchDefault('Revert "feat: x"\r\n\r\nThis reverts commit abc.'), 'revert');
    });
  });

  describe('does not match hand-written messages', () => {
    const cases: string[] = [
      valid.simple,
      valid.withBody,
      notAutoGenerated.mergeProse,
      notAutoGenerated.mergeBranchProse,
      notAutoGenerated.mergeTagProse,
      notAutoGenerated.mergePullRequestNoFrom,
      notAutoGenerated.lowercaseRevert,
      notAutoGenerated.revertNoQuotes,
      notAutoGenerated.revertTrailingProse,
      notAutoGenerated.fixupNoSpace,
      notAutoGenerated.indentedMerge,
      'revert: undo the login change',
      '',
    ];

    for (const message of cases) {
      it(`does not match ${JSON.stringify(message)}`, () => {
        assert.equal(matchDefault(message), null);
      });
    }

    it('does not match a pattern appearing only in the body', () => {
      assert.equal(matchDefault('feat: add login\n\nfixup! not a header'), null);
    });
  });
});

describe('resolveIgnores', () => {
  it('returns the defaults when nothing is specified', () => {
    assert.deepEqual(resolveIgnores(undefined, undefined), defaultIgnores);
  });

  it('returns the defaults when explicitly enabled', () => {
    assert.deepEqual(resolveIgnores(true, undefined), defaultIgnores);
  });

  it('returns an empty list when defaults are disabled with no custom predicates', () => {
    assert.deepEqual(resolveIgnores(false, undefined), []);
  });

  it('appends custom predicates after the defaults, named after the function', () => {
    const startsWithWip = (message: string) => message.startsWith('WIP');
    const resolved = resolveIgnores(undefined, [startsWithWip]);
    assert.equal(resolved.length, defaultIgnores.length + 1);
    assert.equal(resolved.at(-1)!.name, 'startsWithWip');
    assert.equal(resolved.at(-1)!.test, startsWithWip);
  });

  it('uses only custom predicates when defaults are disabled', () => {
    function noWip(message: string): boolean {
      return message.startsWith('WIP');
    }
    const resolved = resolveIgnores(false, [noWip]);
    assert.equal(resolved.length, 1);
    assert.equal(resolved[0]!.name, 'noWip');
  });

  it('falls back to "custom" for anonymous predicates', () => {
    // An arrow inside an array literal gets no name binding (fn.name === '').
    const resolved = resolveIgnores(false, [(message: string) => message === '']);
    assert.equal(resolved[0]!.name, 'custom');
  });

  it('throws when a custom predicate name collides with a built-in pattern', () => {
    const merge = (message: string) => message.startsWith('WIP');
    assert.throws(
      () => resolveIgnores(undefined, [merge]),
      /Custom ignore "merge" conflicts with a built-in ignore pattern of the same name\./,
    );
  });

  it('throws on a built-in name collision even with defaults disabled', () => {
    function revert(message: string): boolean {
      return message.startsWith('undo');
    }
    assert.throws(
      () => resolveIgnores(false, [revert]),
      /Custom ignore "revert" conflicts with a built-in ignore pattern/,
    );
  });

  it('throws when two custom predicates share a name', () => {
    function noWip(message: string): boolean {
      return message.startsWith('WIP');
    }
    const noWipToo = noWip;
    assert.throws(
      () => resolveIgnores(false, [noWip, noWipToo]),
      /Duplicate custom ignore "noWip"/,
    );
  });

  it('throws when two anonymous predicates both fall back to "custom"', () => {
    assert.throws(
      () => resolveIgnores(false, [(m: string) => m === 'a', (m: string) => m === 'b']),
      /Duplicate custom ignore "custom"/,
    );
  });
});

describe('findIgnoreMatch', () => {
  it('returns the first matching entry name', () => {
    const ignores = [
      { name: 'first', test: () => true },
      { name: 'second', test: () => true },
    ];
    assert.equal(findIgnoreMatch('anything', ignores), 'first');
  });

  it('returns null when nothing matches', () => {
    assert.equal(findIgnoreMatch('feat: x', [{ name: 'never', test: () => false }]), null);
  });

  it('returns null for an empty ignore list', () => {
    assert.equal(findIgnoreMatch(autoGenerated.revert, []), null);
  });
});
